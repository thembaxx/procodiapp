import { readFile } from "node:fs/promises";
import path from "node:path";
import { z } from "zod";
import { cacheSchema } from "../src/lib/offers";
import { candidateSchema } from "../src/lib/server/promotion-parser";
import { boundedJson } from "../src/lib/server/bounded-input";
import { hasCompletedDiscovery } from "../src/lib/server/promotion-refresh";

async function main() {
  const repository = process.env.GITHUB_REPOSITORY,
    token = process.env.GITHUB_TOKEN;
  if (
    !repository ||
    !/^[A-Za-z0-9_-]+\/[A-Za-z0-9_.-]+$/.test(repository) ||
    !token ||
    !process.env.DATA_DIR
  )
    throw new Error("Invalid publication configuration.");
  const cache = cacheSchema.parse(
    JSON.parse(await readFile(path.join(process.env.DATA_DIR, "offers.json"), "utf8")),
  );
  const candidates = z
    .array(candidateSchema)
    .max(100)
    .parse(JSON.parse(await readFile(path.join(process.env.DATA_DIR, "candidates.json"), "utf8")));
  if (!hasCompletedDiscovery(cache)) throw new Error("No successful scan to publish.");
  async function api(endpoint: string, method = "GET", body?: unknown, allowMissing = false) {
    const response = await fetch(`https://api.github.com/repos/${repository}/${endpoint}`, {
      method,
      redirect: "error",
      signal: AbortSignal.timeout(10_000),
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: "application/vnd.github+json",
        "Content-Type": "application/json",
        "X-GitHub-Api-Version": "2022-11-28",
      },
      ...(body ? { body: JSON.stringify(body) } : {}),
    });
    if (allowMissing && response.status === 404) return null;
    if (!response.ok) throw new Error("Feed publication request failed.");
    return (await boundedJson(response, 256_000)) as { sha: string; object?: { sha: string } };
  }
  const reference = await api("git/ref/heads/promotion-data", "GET", undefined, true);
  const files = [
    ["offers.json", JSON.stringify(cache, null, 2) + "\n"],
    ["candidates.json", JSON.stringify(candidates, null, 2) + "\n"],
    [
      "README.md",
      "# Scheduled promotion data\n\nGenerated by the free collector on main. offers.json contains validated, source-listed offers. candidates.json contains unconfirmed review leads and must never be treated as live offers. Checkout is not tested.\n",
    ],
  ];
  const tree: { path: string; mode: string; type: string; sha: string }[] = [];
  for (const [filename, content] of files) {
    const blob = await api("git/blobs", "POST", { content, encoding: "utf-8" });
    if (!blob?.sha) throw new Error("Invalid publication blob.");
    tree.push({ path: filename, mode: "100644", type: "blob", sha: blob.sha });
  }
  const createdTree = await api("git/trees", "POST", { tree });
  const parent = reference?.object?.sha;
  const commit = await api("git/commits", "POST", {
    message: "Refresh source-listed promotions",
    tree: createdTree?.sha,
    ...(parent ? { parents: [parent] } : { parents: [] }),
  });
  if (!commit?.sha) throw new Error("Invalid publication commit.");
  if (parent)
    await api("git/refs/heads/promotion-data", "PATCH", { sha: commit.sha, force: false });
  else await api("git/refs", "POST", { ref: "refs/heads/promotion-data", sha: commit.sha });
  console.log("Published validated promotion feed and review candidates to promotion-data.");
}
try {
  await main();
} catch {
  console.error("Promotion feed publication failed; no credentials or source contents are logged.");
  process.exitCode = 1;
}
